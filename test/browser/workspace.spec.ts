import { test, expect } from '@playwright/test'

for (const width of [1280, 375]) test(`empty-list FAB is centered and becomes a trailing add button at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  await expect(page.getByText('First image anchored at origin · crop and rotate before placement.', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Background', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reset', exact: true })).toHaveText('Reset')
  await expect(page.getByRole('switch', { name: 'Translucent overlaps', exact: true })).toBeChecked()
  const list = page.getByRole('region', { name: 'Imported images', exact: true })
  const add = list.getByRole('button', { name: 'Add images', exact: true })
  await expect(add).toHaveClass(/MuiFab-sizeLarge/)
  await expect(list.getByText('Click to add images.', { exact: true })).toBeVisible()
  const region = (await list.boundingBox())!, fab = (await add.boundingBox())!
  expect(fab.x + fab.width / 2).toBeCloseTo(region.x + region.width / 2, 3)
  expect(Math.abs(fab.y + fab.height / 2 - region.y - region.height / 2)).toBeLessThan(32)
  expect(fab.width).toBe(fab.height)
  const image = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 8; c.height = 6
    return c.toDataURL().split(',')[1]
  })
  const choosing = page.waitForEvent('filechooser')
  await add.click()
  await (await choosing).setFiles(['first.png', 'second.png'].map(name => ({ name, mimeType: 'image/png', buffer: Buffer.from(image, 'base64') })))
  await expect(page.getByRole('listitem')).toHaveCount(2)
  await expect(page.locator('.MuiFab-root')).toHaveCount(0)
  await expect(add).toHaveText('Add images')
  await add.scrollIntoViewIfNeeded()
  const last = (await page.getByRole('listitem').last().boundingBox())!, bottom = (await add.boundingBox())!
  expect(bottom.y).toBeGreaterThanOrEqual(last.y + last.height)
  const appending = page.waitForEvent('filechooser')
  await add.click()
  await (await appending).setFiles({ name: 'third.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') })
  await expect(page.getByRole('listitem')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByLabel('Stitch controls', { exact: true }).screenshot({ path: test.info().outputPath('workspace.png') })
})

test('Chinese product identity and concise help follow the selected language', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveTitle('Paper Stitch')
  const help = page.getByRole('button', { name: 'Help', exact: true })
  await help.click()
  let dialog = page.getByRole('dialog', { name: 'About Paper Stitch', exact: true })
  await expect(dialog).toContainText('Stitch screenshots and scanned receipts. Images stay in your browser’s memory and are never uploaded.')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(help).toBeFocused()
  await page.getByRole('button', { name: 'Language', exact: true }).click()
  await page.getByRole('menuitem', { name: '中文', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('拼纸条')
  await expect(page).toHaveTitle('拼纸条')
  await expect(page.getByAltText('拼纸条图标', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '帮助', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '关于拼纸条', exact: true })
  await expect(dialog).toContainText('用于拼接截图和扫描小票。图片仅保存在浏览器内存中，不会上传。')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '横向', exact: true }).click()
  const confirm = page.getByRole('alertdialog', { name: '切换拼接方向？', exact: true })
  await expect(confirm).toContainText('将清除所有图片的偏移、裁剪和旋转参数。')
  await confirm.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '语言', exact: true }).click()
  await page.getByRole('menuitem', { name: 'English', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Paper Stitch')
  await expect(page).toHaveTitle('Paper Stitch')
})
